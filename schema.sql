-- Helper: current role
create or replace function public.my_role()
returns text language sql stable security definer set search_path=public
as $$ select role from public.profiles where id = auth.uid() $$;

-- profiles
drop policy if exists "profiles readable by authenticated" on public.profiles;
create policy "profiles readable by authenticated" on public.profiles for select to authenticated using (true);
drop policy if exists "users update own profile" on public.profiles;
create policy "users update own profile" on public.profiles for update to authenticated using (id=auth.uid()) with check (id=auth.uid());

-- subjects
drop policy if exists "subjects public read" on public.subjects;
create policy "subjects public read" on public.subjects for select using (true);

-- questions
drop policy if exists "questions public read" on public.questions;
create policy "questions public read" on public.questions for select using (true);
drop policy if exists "authenticated create questions" on public.questions;
create policy "authenticated create questions" on public.questions for insert to authenticated with check (author_id=auth.uid());
drop policy if exists "author or manager update questions" on public.questions;
create policy "author or manager update questions" on public.questions for update to authenticated
using (author_id=auth.uid() or public.my_role() in ('subject_manager','admin'))
with check (author_id=auth.uid() or public.my_role() in ('subject_manager','admin'));
drop policy if exists "author or admin delete questions" on public.questions;
create policy "author or admin delete questions" on public.questions for delete to authenticated
using (author_id=auth.uid() or public.my_role()='admin');

-- answers
drop policy if exists "answers public read" on public.answers;
create policy "answers public read" on public.answers for select using (true);
drop policy if exists "authenticated create answers" on public.answers;
create policy "authenticated create answers" on public.answers for insert to authenticated with check (author_id=auth.uid());
drop policy if exists "answer author or manager update" on public.answers;
create policy "answer author or manager update" on public.answers for update to authenticated
using (author_id=auth.uid() or public.my_role() in ('subject_manager','admin'))
with check (author_id=auth.uid() or public.my_role() in ('subject_manager','admin'));

-- courses
drop policy if exists "courses public read" on public.courses;
create policy "courses public read" on public.courses for select using (true);
drop policy if exists "managers create courses" on public.courses;
create policy "managers create courses" on public.courses for insert to authenticated with check (public.my_role() in ('subject_manager','admin'));
drop policy if exists "managers update courses" on public.courses;
create policy "managers update courses" on public.courses for update to authenticated using (public.my_role() in ('subject_manager','admin')) with check (public.my_role() in ('subject_manager','admin'));

-- lessons
drop policy if exists "lessons public read" on public.course_lessons;
create policy "lessons public read" on public.course_lessons for select using (true);
drop policy if exists "managers manage lessons" on public.course_lessons;
create policy "managers manage lessons" on public.course_lessons for all to authenticated using (public.my_role() in ('subject_manager','admin')) with check (public.my_role() in ('subject_manager','admin'));

-- resources
drop policy if exists "approved resources public read" on public.resources;
create policy "approved resources public read" on public.resources for select using (status='approved' or uploader_id=auth.uid() or public.my_role() in ('subject_manager','admin'));
drop policy if exists "authenticated upload resources" on public.resources;
create policy "authenticated upload resources" on public.resources for insert to authenticated with check (uploader_id=auth.uid());
drop policy if exists "uploader or manager update resources" on public.resources;
create policy "uploader or manager update resources" on public.resources for update to authenticated
using (uploader_id=auth.uid() or public.my_role() in ('subject_manager','admin'))
with check (uploader_id=auth.uid() or public.my_role() in ('subject_manager','admin'));

-- KB
drop policy if exists "kb public read" on public.knowledge_base;
create policy "kb public read" on public.knowledge_base for select using (true);
drop policy if exists "managers manage kb" on public.knowledge_base;
create policy "managers manage kb" on public.knowledge_base for all to authenticated using (public.my_role() in ('subject_manager','admin')) with check (public.my_role() in ('subject_manager','admin'));

-- messages
drop policy if exists "messages authenticated read" on public.messages;
create policy "messages authenticated read" on public.messages for select to authenticated using (true);
drop policy if exists "messages authenticated insert own" on public.messages;
create policy "messages authenticated insert own" on public.messages for insert to authenticated with check (author_id=auth.uid());

-- ---------- Storage ----------
insert into storage.buckets (id,name,public) values ('episteme-resources','episteme-resources',true)
on conflict (id) do nothing;

drop policy if exists "public read episteme resources" on storage.objects;
create policy "public read episteme resources" on storage.objects for select using (bucket_id='episteme-resources');

drop policy if exists "authenticated upload episteme resources" on storage.objects;
create policy "authenticated upload episteme resources" on storage.objects for insert to authenticated
with check (bucket_id='episteme-resources');

drop policy if exists "owner delete episteme resources" on storage.objects;
create policy "owner delete episteme resources" on storage.objects for delete to authenticated
using (bucket_id='episteme-resources' and owner_id=auth.uid());

