create extension if not exists pgcrypto;

-- ---------- profiles ----------
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null default 'New member',
  avatar_url text,
  grade text,
  bio text,
  role text not null default 'student' check (role in ('student','subject_manager','admin')),
  created_at timestamptz not null default now()
);

-- ---------- subjects ----------
create table if not exists public.subjects (
  id bigint generated by default as identity primary key,
  name text not null unique,
  code text,
  description text,
  created_at timestamptz not null default now()
);

-- ---------- questions ----------
create table if not exists public.questions (
  id uuid primary key default gen_random_uuid(),
  author_id uuid not null references public.profiles(id) on delete cascade,
  subject_id bigint references public.subjects(id) on delete set null,
  topic text,
  title text not null,
  content text not null,
  status text not null default 'unanswered' check (status in ('unanswered','discussing','answered','archived')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- ---------- answers ----------
create table if not exists public.answers (
  id uuid primary key default gen_random_uuid(),
  question_id uuid not null references public.questions(id) on delete cascade,
  author_id uuid not null references public.profiles(id) on delete cascade,
  content text not null,
  is_verified boolean not null default false,
  created_at timestamptz not null default now()
);

-- ---------- courses ----------
create table if not exists public.courses (
  id uuid primary key default gen_random_uuid(),
  title text not null,
  description text,
  subject_id bigint references public.subjects(id) on delete set null,
  teacher_id uuid references public.profiles(id) on delete set null,
  thumbnail_url text,
  created_at timestamptz not null default now()
);

create table if not exists public.course_lessons (
  id uuid primary key default gen_random_uuid(),
  course_id uuid not null references public.courses(id) on delete cascade,
  title text not null,
  video_url text,
  duration_seconds integer default 0,
  lesson_order integer not null default 0
);

-- ---------- resources ----------
create table if not exists public.resources (
  id uuid primary key default gen_random_uuid(),
  title text not null,
  description text,
  subject_id bigint references public.subjects(id) on delete set null,
  topic text,
  resource_type text not null default 'note' check (resource_type in ('note','paper','handout','tool','other')),
  file_path text,
  external_url text,
  uploader_id uuid references public.profiles(id) on delete set null,
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  created_at timestamptz not null default now()
);

-- ---------- knowledge base ----------
create table if not exists public.knowledge_base (
  id uuid primary key default gen_random_uuid(),
  question_id uuid references public.questions(id) on delete set null,
  title text not null,
  summary text,
  subject_id bigint references public.subjects(id) on delete set null,
  topic text,
  created_at timestamptz not null default now()
);

-- ---------- real-time community messages ----------
create table if not exists public.messages (
  id uuid primary key default gen_random_uuid(),
  channel text not null,
  author_id uuid not null references public.profiles(id) on delete cascade,
  content text not null,
  created_at timestamptz not null default now()
);

create index if not exists questions_created_at_idx on public.questions(created_at desc);
create index if not exists questions_subject_idx on public.questions(subject_id);
create index if not exists answers_question_idx on public.answers(question_id);
create index if not exists messages_channel_created_idx on public.messages(channel, created_at desc);
create index if not exists resources_subject_idx on public.resources(subject_id);

-- ---------- updated_at trigger ----------
create or replace function public.set_updated_at()
returns trigger language plpgsql as $$
begin new.updated_at = now(); return new; end; $$;

drop trigger if exists questions_updated_at on public.questions;
create trigger questions_updated_at before update on public.questions
for each row execute function public.set_updated_at();

-- ---------- automatically create profile on signup ----------
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.profiles (id, username)
  values (new.id, coalesce(new.raw_user_meta_data->>'username', split_part(coalesce(new.email,''),'@',1), 'New member'))
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

